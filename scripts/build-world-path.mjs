// Generates src/lib/world-path.ts: one simplified SVG path of the world's land,
// in an equirectangular projection on a 360 x 180 canvas (x = lon + 180, y = 90 - lat).
// Data: Natural Earth via world-atlas (public domain). Run: node scripts/build-world-path.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { geoEquirectangular, geoPath } from 'd3-geo';
import { feature } from 'topojson-client';

const require = createRequire(import.meta.url);
const topo = JSON.parse(readFileSync(require.resolve('world-atlas/land-110m.json'), 'utf8'));
const land = feature(topo, topo.objects.land);
const projection = geoEquirectangular().scale(180 / Math.PI).translate([180, 90]).precision(0.1);
const d = geoPath(projection)(land)
  .replace(/(\d+\.\d)\d+/g, '$1'); // one decimal is plenty at this size
writeFileSync(
  new URL('../src/lib/world-path.ts', import.meta.url),
  `// Generated by scripts/build-world-path.mjs from Natural Earth (public domain). Do not edit.\nexport const WORLD_VIEWBOX = '0 0 360 180';\nexport const WORLD_LAND_PATH =\n  '${d}';\n`,
);
console.log('world path bytes:', d.length);
